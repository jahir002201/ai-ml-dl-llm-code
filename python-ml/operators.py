a = 10
b = 3

# Arithmetic
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

# Comparison
print("Equal:", a == b)
print("Not equal:", a != b)
print("Greater:", a > b)
print("Less:", a < b)

# Logical
x = 20

print("AND:", x > 10 and x < 30)
print("OR:", x < 10 or x > 15)
print("NOT:", not x < 10)

# Assignment
number = 10

number += 5
print("+=:", number)

number -= 2
print("-=:", number)

number *= 2
print("*=:", number)

number /= 2
print("/=:", number)

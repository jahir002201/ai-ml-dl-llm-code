# Multiplication before addition

result = 10 + 5 * 2
print(result)

# Parentheses first

result = (10 + 5) * 2
print(result)

# Exponentiation

result = 2 ** 3 * 4
print(result)

# Complex expression

result = 10 + 2 * 3 ** 2
print(result)

# Left-to-right example

result = 100 / 10 * 2
print(result)
